// Need to use the React-specific entry point to import `createApi`
import { createApi, fetchBaseQuery } from "@reduxjs/toolkit/query/react"

// Define a service using a base URL and expected endpoints
export const iiifContentSearchApiSlice = createApi({
  baseQuery: fetchBaseQuery(),
  reducerPath: "iiifContentSearchApi",
  // Tag types are used for caching and invalidation.
  tagTypes: ["IiifContentSearch"],
  endpoints: build => ({
    // Supply generics for the return type (in this case `QuotesApiResponse`)
    // and the expected query argument. If there is no argument, use `void`
    // for the argument type instead.
    getIiifContentSearch: build.infiniteQuery({
      infiniteQueryOptions: {
        initialPageParam: undefined,
        // IIIF Content Search v1: each page links to the next page by URL
        getNextPageParam: (lastPage) => lastPage?.next,
      },
      query: ({queryArg, pageParam}) => {
        if (pageParam) {
          return { url: pageParam }
        } else {
          const separator = queryArg.endpoint.includes('?') ? '&' : '?'
          return { url: `${queryArg.endpoint}${separator}${new URLSearchParams({ q: queryArg.query })}` }
        }
      },
      // `providesTags` determines which 'tag' is attached to the
      // cached data returned by the query.
      providesTags: (_result, _error, query) => [{ type: "IiifContentSearch", query }],
    }),
  }),
})

// Hooks are auto-generated by RTK-Query
// Same as `searchApiSlice.endpoints.getIiifContentSearch.useQuery`
export const { useGetIiifContentSearchInfiniteQuery } = iiifContentSearchApiSlice

export default iiifContentSearchApiSlice
